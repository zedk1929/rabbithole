"""
Human Rating Sheet Generator for Viewing Path Evaluation.
Generates structured Markdown and CSV rating sheets comparing the Rabbithole path
against the Search Order Baseline.
All ratings are left blank for human evaluation.
"""
import csv
import io
from typing import List, Dict, Any


RUBRIC_HEADER = """# Rabbithole Viewing Path Evaluation — Human Rating Sheet

This rating sheet is designed for human evaluators to score viewing paths generated by **Rabbithole** against a **Search Order Baseline** across 10 diverse curiosity profiles.

> [!IMPORTANT]
> **Instructions for Evaluator**:
> 1. Watch or inspect each video in order (Step 1 through Step 5).
> 2. Rate each individual video on the 1–5 scale defined below.
> 3. Leave no judgments invented; all scores must reflect human inspection.
> 4. Record diagnostic reasons explaining **why** a viewing path succeeded or failed.

---

### Scoring Rubric (1 to 5 Scale)

| Metric | 1 (Poor / Low) | 3 (Moderate) | 5 (Exceptional / High) |
| :--- | :--- | :--- | :--- |
| **Interest** | Dull, flat, or disengaging presentation. | Moderately engaging overview. | Captivating, thought-provoking, and memorable. |
| **Depth** | Superficial recap, filler, or shallow listicle. | Informative with decent technical context. | Dense, rigorous, primary-source, or first-principles breakdown. |
| **Surprise** | Cliché, mainstream common knowledge. | Somewhat fresh angle or niche subtopic. | True serendipity; off the radar, high-novelty archive. |
| **Relevance** | Off-topic drift; ignores stated goals/avoids. | Broadly related to the general domain. | High-signal match for the user's explicit learning goal. |
| **Fit After Prev** | Jarring, abrupt disconnect from video N-1. | Loose or acceptable thematic transition. | Cohesive, natural intellectual progression (N/A for Video 1). |

---
"""


def generate_markdown_rating_sheet(evaluation_data: List[Dict[str, Any]], metadata: Dict[str, Any]) -> str:
    """Generates a complete human-readable Markdown rating sheet."""
    lines = [RUBRIC_HEADER]

    lines.append(f"**Evaluation Run**: `{metadata.get('run_id', 'unknown')}` | **Date**: `{metadata.get('timestamp', 'unknown')}`")
    lines.append(f"**Retrieval Mode**: `{metadata.get('source_mode', 'unknown')}` | **LLM Expansion**: `{metadata.get('llm_mode', 'unknown')}`")
    lines.append(f"**Profiles Evaluated**: `{len(evaluation_data)}` | **Status**: `Ratings Unscored (Ready for Human Review)`\n")
    lines.append("---\n")

    for p_idx, item in enumerate(evaluation_data, 1):
        prof = item["profile"]
        prefs = prof["preferences"]
        app_path = item.get("app_path", [])
        baseline_path = item.get("baseline_path", [])

        lines.append(f"## Profile {p_idx:02d}: {prof['title']} (`{prof['id']}`)")
        lines.append(f"**Category**: `{prof.get('category', 'custom')}` — *{prof.get('description', '')}*")
        lines.append(f"- **Core Interests**: {prefs['interests']}")
        lines.append(f"- **Serendipity Dial**: `{prefs.get('serendipity_level', 3)}/5`")
        if prefs.get("avoid_topics"):
            lines.append(f"- **Avoid Topics**: {prefs['avoid_topics']}")
        if prefs.get("familiar_topics"):
            lines.append(f"- **Familiar Knowledge**: {prefs['familiar_topics']}")
        if prefs.get("learning_goal"):
            lines.append(f"- **Session Goal**: {prefs['learning_goal']}")
        if prefs.get("explore_topics"):
            lines.append(f"- **Explore Topics**: {prefs['explore_topics']}")
        lines.append(f"- **Parameters**: Depth `{prefs.get('depth_level', 'curious_explorer')}` | Min Duration `{prefs.get('min_duration_minutes', 6)}m`\n")

        # Table 1: Rabbithole Ordered Path
        lines.append("### Path A: Rabbithole Ordered Journey\n")
        lines.append("| # | Step & Role | Video Title | Channel | Duration | Interest (1-5) | Depth (1-5) | Surprise (1-5) | Relevance (1-5) | Fit After Prev (1-5) | Notes |")
        lines.append("|---|---|---|---|---|:---:|:---:|:---:|:---:|:---:|---|")

        if not app_path:
            lines.append("| - | *No path generated* | - | - | - | - | - | - | - | - | - |")
        else:
            for v_idx, v in enumerate(app_path, 1):
                role = v.get("path_step", f"Step {v_idx}")
                q_type = v.get("source_query_type", "")
                role_label = f"**{role}**<br><sub>{q_type}</sub>"
                title = v.get("title", "Untitled").replace("|", "-")
                url = v.get("url", "#")
                channel = v.get("channel", "Unknown").replace("|", "-")
                dur = v.get("duration_formatted", "")
                fit_cell = "N/A" if v_idx == 1 else "[ ]"
                lines.append(f"| {v_idx} | {role_label} | [{title}]({url}) | {channel} | {dur} | [ ] | [ ] | [ ] | [ ] | {fit_cell} | [ ] |")

        lines.append("\n**Rabbithole Path Diagnostics & Outcome**:")
        lines.append("- Overall Path Coherence (1-5): `[ ]`")
        lines.append("- Conceptual Progression (1-5): `[ ]`")
        lines.append("- Path Outcome Verdict: `[ ] SUCCESS` &nbsp;&nbsp; `[ ] PARTIAL` &nbsp;&nbsp; `[ ] FAILURE`")
        lines.append("- Failure / Success Reasons (check all that apply):")
        lines.append("  - `[ ]` Natural, progressive narrative bridge across concepts")
        lines.append("  - `[ ]` Surfaced authentic high-signal archival gems")
        lines.append("  - `[ ]` Successfully avoided forbidden/superficial tropes")
        lines.append("  - `[ ]` Abrupt or jarring topic leap")
        lines.append("  - `[ ]` Repetitive content (redundant videos in same hole)")
        lines.append("  - `[ ]` Overly shallow or overly academic jargon")
        lines.append("  - `[ ]` Missed core learning goal")
        lines.append("- Evaluator Notes on Path A:")
        lines.append("  > [Write qualitative observations here...]\n")

        # Table 2: Search Result Order Baseline
        lines.append("### Path B: Search Result Order Baseline (Raw Eligible Search Order)\n")
        lines.append("| # | Search Rank | Video Title | Channel | Duration | Interest (1-5) | Depth (1-5) | Surprise (1-5) | Relevance (1-5) | Fit After Prev (1-5) | Notes |")
        lines.append("|---|---|---|---|---|:---:|:---:|:---:|:---:|:---:|---|")

        if not baseline_path:
            lines.append("| - | *No baseline candidates* | - | - | - | - | - | - | - | - | - |")
        else:
            for b_idx, b in enumerate(baseline_path, 1):
                s_rank = f"Rank #{b.get('original_search_index', b_idx) + 1}"
                title = b.get("title", "Untitled").replace("|", "-")
                url = b.get("url", "#")
                channel = b.get("channel", "Unknown").replace("|", "-")
                dur = b.get("duration_formatted", "")
                fit_cell = "N/A" if b_idx == 1 else "[ ]"
                lines.append(f"| {b_idx} | {s_rank} | [{title}]({url}) | {channel} | {dur} | [ ] | [ ] | [ ] | [ ] | {fit_cell} | [ ] |")

        lines.append("\n**Baseline Path Diagnostics & Outcome**:")
        lines.append("- Overall Path Coherence (1-5): `[ ]`")
        lines.append("- Conceptual Progression (1-5): `[ ]`")
        lines.append("- Path Outcome Verdict: `[ ] SUCCESS` &nbsp;&nbsp; `[ ] PARTIAL` &nbsp;&nbsp; `[ ] FAILURE`")
        lines.append("- Evaluator Notes on Path B:")
        lines.append("  > [Write qualitative observations here...]\n")
        lines.append("---\n")

    return "\n".join(lines)


def generate_csv_rating_sheet(evaluation_data: List[Dict[str, Any]]) -> str:
    """Generates a CSV rating sheet formatted for spreadsheet import."""
    output = io.StringIO()
    writer = csv.writer(output)

    # Header
    writer.writerow([
        "profile_id",
        "profile_title",
        "profile_category",
        "path_type",
        "step_number",
        "step_label_or_rank",
        "query_type",
        "video_id",
        "video_title",
        "channel",
        "duration_formatted",
        "url",
        "interest_score_1_to_5",
        "depth_score_1_to_5",
        "surprise_score_1_to_5",
        "relevance_score_1_to_5",
        "fit_after_previous_1_to_5",
        "video_evaluator_notes",
        "path_overall_coherence_1_to_5",
        "path_verdict_pass_fail_partial",
        "path_success_or_failure_reasons",
        "path_evaluator_notes",
    ])

    for item in evaluation_data:
        prof = item["profile"]
        p_id = prof["id"]
        p_title = prof["title"]
        p_cat = prof.get("category", "")

        # Write Rabbithole Path rows
        for idx, v in enumerate(item.get("app_path", []), 1):
            writer.writerow([
                p_id,
                p_title,
                p_cat,
                "rabbithole_path",
                idx,
                v.get("path_step", f"Step {idx}"),
                v.get("source_query_type", ""),
                v.get("video_id", ""),
                v.get("title", ""),
                v.get("channel", ""),
                v.get("duration_formatted", ""),
                v.get("url", ""),
                "",  # interest_score_1_to_5 (blank)
                "",  # depth_score_1_to_5 (blank)
                "",  # surprise_score_1_to_5 (blank)
                "",  # relevance_score_1_to_5 (blank)
                "N/A" if idx == 1 else "",  # fit_after_previous_1_to_5 (blank)
                "",  # video_evaluator_notes (blank)
                "",  # path_overall_coherence (blank)
                "",  # path_verdict (blank)
                "",  # path_success_or_failure_reasons (blank)
                "",  # path_evaluator_notes (blank)
            ])

        # Write Search Baseline rows
        for idx, b in enumerate(item.get("baseline_path", []), 1):
            writer.writerow([
                p_id,
                p_title,
                p_cat,
                "search_order_baseline",
                idx,
                f"SearchRank #{b.get('original_search_index', idx) + 1}",
                b.get("source_query_type", ""),
                b.get("video_id", ""),
                b.get("title", ""),
                b.get("channel", ""),
                b.get("duration_formatted", ""),
                b.get("url", ""),
                "",  # interest_score_1_to_5 (blank)
                "",  # depth_score_1_to_5 (blank)
                "",  # surprise_score_1_to_5 (blank)
                "",  # relevance_score_1_to_5 (blank)
                "N/A" if idx == 1 else "",  # fit_after_previous_1_to_5 (blank)
                "",  # video_evaluator_notes (blank)
                "",  # path_overall_coherence (blank)
                "",  # path_verdict (blank)
                "",  # path_success_or_failure_reasons (blank)
                "",  # path_evaluator_notes (blank)
            ])

    return output.getvalue()
